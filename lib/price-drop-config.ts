// 値下げ経路の候補条件のうち、運用で見直す値（値下げ幅の下限・価格の下限・除外する語）をまとめた設定。
// 語の一覧は SQL に埋め込むため、引用符・%・_ を含めない。

// 値下げ率がこの値（%）未満、または値下げ額がこの値（円）未満の商品は候補にしない。
// ¥980 → ¥979 のような、誤差に近い値下げを紹介しないため。
export const MIN_DROP_RATE_PERCENT = 3;
export const MIN_DROP_AMOUNT_YEN = 100;

// 本体でない商品は、前回の価格がこの値（円）以上のときだけ候補にする。本体は価格に関わらず対象にする。
export const MIN_PREVIOUS_PRICE_YEN = 3000;

// 商品名にこれらの語を含む商品は候補にしない。値引きの条件・期限を商品名に書いた出品で、
// 商品名の価格が条件なしの値段なのか分からないため。
// 全角・半角、大文字・小文字の違いでもれないよう、NFKC で正規化し、大文字・小文字を区別せずに比べる。
export const PRICE_DROP_PROMO_KEYWORDS = ["クーポン", "割引", "半額", "OFF", "オフ", "還元", "セール", "まで"];

// 本体でない商品のうち、商品名にこれらの語を含むものはアクセサリーとして候補にしない。
// Apple Watch の本体は「〜ケースと〜スポーツバンド」のように同じ語を含むため、本体と判定した商品には使わない。
export const ACCESSORY_KEYWORDS = ["バンド", "チャーム", "ケース", "フィルム", "ケーブル"];
